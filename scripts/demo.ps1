<#
.SYNOPSIS
  Run the whole isd-bus-routing stack on this computer for demos and
  beta testing. See docs/demo.md.

.DESCRIPTION
  up           Build and start everything, run migrations, and (first time
               only) load the fictional demo district. Open http://localhost:8080
  share        Same as up, plus a free temporary public HTTPS link for testers.
  unshare      Turn the public link off again (the demo keeps running here).
  stop         Stop everything. Data is kept; `up` brings it back.
  status       Show what's running.
  logs         Follow the logs (Ctrl+C to stop following).
  credentials  Print the demo logins again.
  reset        Delete ALL demo data and secrets and start over from scratch.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\demo.ps1 up
#>
param(
    [Parameter(Position = 0)]
    [ValidateSet('up', 'share', 'unshare', 'stop', 'status', 'logs', 'credentials', 'reset')]
    [string]$Command = 'up'
)

$ErrorActionPreference = 'Stop'
$RepoRoot = Split-Path -Parent $PSScriptRoot
Set-Location $RepoRoot

$EnvFile = Join-Path $RepoRoot '.env.demo'
$PgPasswordFile = Join-Path $RepoRoot 'secrets\demo_postgres_password.txt'
$CredentialsJson = Join-Path $RepoRoot 'secrets\demo-credentials.json'
$LocalUrl = 'http://localhost:8080'
$ComposeArgs = @('compose', '--env-file', $EnvFile, '-f', 'docker-compose.prod.yml', '-f', 'docker-compose.demo.yml')

function Write-Step([string]$Message) { Write-Host "==> $Message" -ForegroundColor Cyan }

function Invoke-Compose {
    # Docker writes progress to stderr; that's normal, so only the exit
    # code decides success.
    & docker @ComposeArgs @args
    if ($LASTEXITCODE -ne 0) { throw "docker compose $($args -join ' ') failed (exit code $LASTEXITCODE)." }
}

function New-RandomHex([int]$Bytes) {
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
    return (($buffer | ForEach-Object { $_.ToString('x2') }) -join '')
}

function New-FernetKey {
    # 32 random bytes, url-safe base64: the format ISD_API_MFA_ENCRYPTION_KEY needs.
    $buffer = New-Object byte[] 32
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
    return [Convert]::ToBase64String($buffer).Replace('+', '-').Replace('/', '_')
}

function Write-TextFile([string]$Path, [string]$Text) {
    # UTF-8 without a BOM and LF line endings: a BOM would corrupt the
    # first variable name in .env.demo.
    [System.IO.File]::WriteAllText($Path, $Text.Replace("`r`n", "`n"))
}

function Test-DockerEngine {
    # Windows PowerShell 5.1 turns a redirected native stderr line into an
    # error record, which 'Stop' would make fatal; scope it to 'Continue'.
    $ErrorActionPreference = 'Continue'
    & docker info *> $null
    return ($LASTEXITCODE -eq 0)
}

function Get-TunnelLogs {
    $ErrorActionPreference = 'Continue'  # see Test-DockerEngine
    return (& docker @ComposeArgs --profile share logs cloudflared 2>&1 | Out-String)
}

function Assert-Docker {
    if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
        throw 'Docker is not installed. Install Docker Desktop (https://www.docker.com/products/docker-desktop/) and run this again.'
    }
    if (Test-DockerEngine) { return }

    $desktop = Join-Path $env:ProgramFiles 'Docker\Docker\Docker Desktop.exe'
    if (-not (Test-Path $desktop)) { throw 'Docker is installed but not running. Start Docker Desktop and run this again.' }
    Write-Step 'Starting Docker Desktop (this can take a minute)...'
    Start-Process $desktop
    for ($i = 0; $i -lt 90; $i++) {
        Start-Sleep -Seconds 2
        if (Test-DockerEngine) { return }
    }
    throw 'Docker Desktop did not finish starting. Wait for it to say "Engine running", then run this again.'
}

function Initialize-Secrets {
    # Generated once, on first run, and never printed. Both files are
    # gitignored (.env.* and secrets/*).
    if ((Test-Path $EnvFile) -and (Test-Path $PgPasswordFile)) {
        Add-MfaKey
        return
    }
    Write-Step 'Generating demo secrets (first run only)...'
    New-Item -ItemType Directory -Force (Split-Path $PgPasswordFile) | Out-Null
    # Hex only, so it needs no escaping inside the connection URL below.
    $dbSecret = New-RandomHex 24
    Write-TextFile $PgPasswordFile $dbSecret
    # Assembled from parts at run time; the random value never exists in
    # this file, only in the gitignored outputs.
    $dbUrl = 'postgresql+psycopg://isd:' + $dbSecret + '@postgres:5432/isd_api'
    $jwtSecret = New-RandomHex 32
    Write-TextFile $EnvFile (@(
            '# Generated by scripts/demo.ps1 for the LOCAL DEMO only. Never commit this file.',
            'POSTGRES_USER=isd',
            'POSTGRES_DB=isd_api',
            "ISD_API_DATABASE_URL=$dbUrl",
            "ISD_API_JWT_SECRET_KEY=$jwtSecret",
            "ISD_API_CORS_ALLOWED_ORIGINS=[`"$LocalUrl`"]",
            '# The web app calls the api on its own origin under /api, so the same',
            '# build works at localhost and at the public tunnel address.',
            'PUBLIC_API_ORIGIN=/api',
            '# A bare port makes Caddy serve plain HTTP there instead of fetching a certificate.',
            'CADDY_DOMAIN=:8080',
            ''
        ) -join "`n")
    Add-MfaKey
}

function Add-MfaKey {
    # Demos made before two-step sign-in (PR #67) have no key yet; add one
    # without touching anything else in .env.demo.
    $current = [System.IO.File]::ReadAllText($EnvFile)
    if ($current -match '(?m)^ISD_API_MFA_ENCRYPTION_KEY=') { return }
    if ($current.Length -gt 0 -and -not $current.EndsWith("`n")) { $current += "`n" }
    $key = New-FernetKey
    Write-TextFile $EnvFile ($current + "# Encrypts authenticator secrets (two-step sign-in).`nISD_API_MFA_ENCRYPTION_KEY=$key`n")
}

function Show-Credentials {
    if (-not (Test-Path $CredentialsJson)) {
        Write-Host 'No demo logins saved yet. Run: scripts\demo.ps1 up' -ForegroundColor Yellow
        return
    }
    $accounts = Get-Content $CredentialsJson -Raw | ConvertFrom-Json
    Write-Host ''
    Write-Host 'Demo logins (one per role; saved in secrets\demo-credentials.json):' -ForegroundColor Green
    $accounts | Format-Table -AutoSize -Wrap @{ Label = 'Role'; Expression = { $_.role } },
    @{ Label = 'Email'; Expression = { $_.email } },
    @{ Label = 'Password'; Expression = { $_.password } },
    @{ Label = 'What to try'; Expression = { $_.note } } | Out-Host
}

function Start-Demo {
    Assert-Docker
    Initialize-Secrets

    Write-Step 'Building and starting the stack (the first build takes a few minutes)...'
    Invoke-Compose up -d --build --wait postgres mailpit api web caddy

    Write-Step 'Applying database migrations...'
    Invoke-Compose exec -T api alembic upgrade head

    if (-not (Test-Path $CredentialsJson)) {
        Write-Step 'Loading the fictional demo district...'
        $output = & docker @ComposeArgs exec -T api python scripts/seed_demo.py
        $code = $LASTEXITCODE
        if ($code -eq 0) {
            Write-TextFile $CredentialsJson (($output | Out-String).Trim())
        }
        elseif ($code -eq 3) {
            Write-Host 'The database already has users, so the demo seed was skipped.' -ForegroundColor Yellow
            Write-Host 'Its logins are not saved here. Run "scripts\demo.ps1 reset" for a clean demo.' -ForegroundColor Yellow
        }
        else { throw "Loading the demo data failed (exit code $code). See the messages above." }
    }

    Write-Host ''
    Write-Host "The demo is running at $LocalUrl (only reachable from this computer)." -ForegroundColor Green
    Write-Host 'Emails it sends (password resets, new-account set-up) land in the test inbox at http://localhost:8025.' -ForegroundColor Green
    Show-Credentials
}

function Start-Share {
    Start-Demo
    Write-Step 'Opening a temporary public HTTPS link via Cloudflare quick tunnel...'
    Invoke-Compose --profile share up -d cloudflared
    $url = $null
    for ($i = 0; $i -lt 30 -and -not $url; $i++) {
        Start-Sleep -Seconds 2
        $match = [regex]::Match((Get-TunnelLogs), 'https://[a-z0-9-]+\.trycloudflare\.com')
        if ($match.Success) { $url = $match.Value }
    }
    if (-not $url) { throw 'The tunnel did not report a public address. Check: scripts\demo.ps1 logs' }

    Write-Host ''
    Write-Host "Share this link with your testers:  $url" -ForegroundColor Green
    Write-Host 'Anyone with the link can reach the login page while sharing is on.' -ForegroundColor Yellow
    Write-Host 'Give each tester only the login(s) they need, or better, create them their own' -ForegroundColor Yellow
    Write-Host 'account on the Users page. Turn sharing off afterwards: scripts\demo.ps1 unshare' -ForegroundColor Yellow
    Write-Host 'The link changes each time sharing restarts.' -ForegroundColor Yellow
}

switch ($Command) {
    'up' { Start-Demo }
    'share' { Start-Share }
    'unshare' {
        Invoke-Compose --profile share stop cloudflared
        Invoke-Compose --profile share rm -f cloudflared
        Write-Host "Public link is off. The demo is still running at $LocalUrl." -ForegroundColor Green
    }
    'stop' {
        Invoke-Compose --profile share down
        Write-Host 'Stopped. Your demo data is kept; "scripts\demo.ps1 up" starts it again.' -ForegroundColor Green
    }
    'status' { Invoke-Compose --profile share ps }
    'logs' { Invoke-Compose --profile share logs -f --tail 100 }
    'credentials' { Show-Credentials }
    'reset' {
        Write-Host 'This permanently deletes ALL demo data (database, logins) and the demo secrets.' -ForegroundColor Yellow
        $answer = Read-Host 'Type RESET to continue'
        if ($answer -cne 'RESET') { Write-Host 'Cancelled; nothing was deleted.'; return }
        if (Test-Path $EnvFile) { Invoke-Compose --profile share down -v }
        foreach ($f in @($EnvFile, $PgPasswordFile, $CredentialsJson)) {
            if (Test-Path $f) { Remove-Item $f }
        }
        Write-Host 'Demo reset. Run "scripts\demo.ps1 up" to start fresh.' -ForegroundColor Green
    }
}
